router = APIRouter()


@router.get("/{user_id}/dashboard", response_model=DashboardSummary)
def get_dashboard_summary(user_id: str):
    """
    Get complete dashboard summary for a user.
    Includes user profile, wallet state, credit score, today's sales, and recent activity.
    """
    with db_session() as db:
        # Get user profile
        user = db.get(User, user_id)
        if not user:
            raise HTTPException(status_code=404, detail="User not found")

        # Get wallet state
        wallet_record = db.execute(
            select(Wallet).where(Wallet.user_id == user_id)
        ).scalar_one_or_none()
        if not wallet_record:
            raise HTTPException(status_code=404, detail="Wallet not found")

        # Get latest credit score
        credit_score = db.execute(
            select(CreditScore)
            .where(CreditScore.user_id == user_id)
            .order_by(desc(CreditScore.calculated_at))
            .limit(1)
        ).scalar_one_or_none()

        # Get today's sales metrics
        today = date.today()
        today_sales = db.execute(
            select(SalesMetrics).where(
                SalesMetrics.user_id == user_id,
                SalesMetrics.date == today
            )
        ).scalar_one_or_none()

        # Get recent activity (last 5 sales transactions)
        recent_sales = db.execute(
            select(SalesTransaction)
            .where(SalesTransaction.owner_id == user_id)
            .order_by(desc(SalesTransaction.transaction_date))
            .limit(5)
        ).scalars().all()

        # Convert sales to transaction summaries
        recent_activity = []
        for sale in recent_sales:
            recent_activity.append({
                "id": sale.id,
                "amount_kobo": sale.total_amount_kobo,
                "type": "sale",
                "description": f"{sale.order_type.upper()} sale ({sale.status})",
                "created_at": sale.transaction_date
            })

        # Get market ticker (In a real app, this would come from a cache/external API)
        market_ticker = [
            {"symbol": "USD/NGN", "price": "1,450.00", "change": "+0.45%", "positive": True},
            {"symbol": "BRENT", "price": "85.20", "change": "-1.2%", "positive": False},
            {"symbol": "COCOA", "price": "4,120", "change": "+2.1%", "positive": True},
            {"symbol": "INFLATION", "price": "29.8%", "change": "+0.5%", "positive": False},
        ]

        # Generate Intelligence (AI Briefing)
        # In a real app, this would be generated by an LLM or expert system analyzing DB metrics
        intelligence = []
        if today_sales and today_sales.total_sales_kobo > 0:
            intelligence.append({
                "category": "OPPORTUNITY",
                "source": "Sales AI",
                "timeAgo": "Just now",
                "headline": "High Sales Velocity",
                "subtitle": f"Your sales are up {today_sales.vs_yesterday_percent}% vs yesterday. Consider restocking top items."
            })
        
        if not intelligence:
            intelligence.append({
                "category": "TIPS",
                "source": "Business Coach",
                "timeAgo": "2h ago",
                "headline": "Optimize Inventory",
                "subtitle": "You have 3 items with low stock. Replenish now to avoid missed sales."
            })

        # Calculate Sales Streak
        # In a real app, this would query SalesMetrics for consecutive active days
        past_metrics = db.execute(
            select(SalesMetrics)
            .where(SalesMetrics.user_id == user_id)
            .order_by(desc(SalesMetrics.date))
            .limit(10)
        ).scalars().all()
        
        streak = 0
        for m in past_metrics:
            if m.transaction_count > 0:
                streak += 1
            else:
                break
        
        sales_streak = {
            "streak_days": streak,
            "total_days": 7, # Weekly target
            "points_earned": streak * 10,
            "next_reward_tier": "Silver" if streak < 5 else "Gold"
        }

        # Community Stats
        total_users = db.execute(select(func.count(User.id))).scalar() or 0
        community_stats = {
            "total_members": total_users,
            "active_discussions": 12, # In a real app, this would query a forums/chat service
            "new_opportunities": 5
        }

        # Fetch Loan Repayment Info
        next_loan = db.execute(
            select(Loan)
            .where(Loan.user_id == user_id, Loan.status == "active")
            .order_by(Loan.next_repayment_date.asc())
        ).scalars().first()

        wallet = {
            "balance_kobo": wallet_record.balance_kobo,
            "credit_limit_kobo": 50000000, # 500k limit
            "available_credit_kobo": 35000000,
            "total_debt_kobo": next_loan.outstanding_balance_kobo if next_loan else 0,
            "next_repayment_date": next_loan.next_repayment_date if next_loan else None,
            "repayment_amount_kobo": next_loan.outstanding_balance_kobo if next_loan else 0 # Simplified
        }

        return {
            "user": user,
            "wallet": wallet,
            "credit_score": credit_score,
            "today_sales": today_sales,
            "recent_activity": recent_activity,
            "market_ticker": market_ticker,
            "intelligence": intelligence,
            "sales_streak": sales_streak,
            "community_stats": community_stats
        }


@router.get("/{user_id}/sales-metrics", response_model=List[SalesMetricsOut])
def get_sales_metrics(user_id: str, limit: int = 30):
    """
    Get sales metrics for a user.
    Returns last N days of sales metrics (default 30 days).
    """
    with db_session() as db:
        # Verify user exists
        user = db.get(User, user_id)
        if not user:
            raise HTTPException(status_code=404, detail="User not found")

        metrics = db.execute(
            select(SalesMetrics)
            .where(SalesMetrics.user_id == user_id)
            .order_by(desc(SalesMetrics.date))
            .limit(limit)
        ).scalars().all()

        return metrics


